package br.com.carstore.model;

public class Car {

    private String name;
    private String color;
    private String model;

    public Car(String name) {
        this.name = name;
    }

    public String getName() {
        return name;
    }

    public String getColor() {
        return color;
    }


    public String getModel() {
        return model;
    }

}
